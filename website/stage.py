"""Stage the repository's Markdown docs for the MkDocs site.

The Markdown files stay where they are: the app fetches documentation/HelpDocs
from GitHub raw on main at runtime, and the README links into documentation/.
This script copies them into website/.stage (the MkDocs docs_dir) and rewrites
relative links so they resolve inside the site. A link to a repository file
that is not part of the site (docker-compose.yml, env.example) points to the
file on GitHub. A link to a file that does not exist fails the build.

The site's look comes from the app itself: the fonts and design tokens are
taken from frontend/assets/css/ui.css at build time (see theme()), so the
two cannot drift apart.

Usage: python website/stage.py
"""

import posixpath
import re
import shutil
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
STAGE = REPO / "website" / ".stage"
GITHUB_BLOB = "https://github.com/ShlomiPorush/mailcow-logs-viewer/blob/main/"

# Internal documents that are not published
EXCLUDE = {"documentation/UI_Behavior_Catalog.md"}

LINK = re.compile(r"(\]\()([^)\s]+)(\))")

# GitHub callouts ("> [!NOTE]"), which GitHub and the app's help render as
# boxes, become Material admonitions
CALLOUT = re.compile(r"^> \[!(NOTE|TIP|IMPORTANT|WARNING|CAUTION)\][ \t]*\n((?:>.*(?:\n|$))*)", re.M)
CALLOUT_KIND = {"NOTE": "note", "TIP": "tip", "IMPORTANT": 'info "Important"',
                "WARNING": "warning", "CAUTION": 'danger "Caution"'}


def callouts(text):
    def fix(match):
        body = [re.sub(r"^> ?", "", line) for line in match.group(2).splitlines()]
        lines = "".join(f"    {line}\n" if line.strip() else "\n" for line in body)
        return f"!!! {CALLOUT_KIND[match.group(1)]}\n\n{lines}"

    return CALLOUT.sub(fix, text)


def pages():
    """Map each published source file (repo-relative) to its staged path."""
    mapping = {"README.md": "index.md", "CHANGELOG.md": "changelog.md"}
    for path in sorted((REPO / "documentation").rglob("*.md")):
        rel = path.relative_to(REPO).as_posix()
        if rel not in EXCLUDE:
            mapping[rel] = rel[len("documentation/"):]
    return mapping


def rewrite(source, text, mapping, errors):
    source_dir = posixpath.dirname(source)
    stage_dir = posixpath.dirname(mapping[source])

    def fix(match):
        target = match.group(2)
        if re.match(r"^[a-z][a-z0-9+.-]*:", target, re.I) or target.startswith("#"):
            return match.group(0)
        path, _, anchor = target.partition("#")
        anchor = "#" + anchor if anchor else ""
        if path.startswith("/"):
            resolved = posixpath.normpath(path.lstrip("/"))
        else:
            resolved = posixpath.normpath(posixpath.join(source_dir, path))
        if resolved in mapping:
            new = posixpath.relpath(mapping[resolved], stage_dir or ".")
        elif resolved.startswith("images/") and (REPO / resolved).is_file():
            new = posixpath.relpath(resolved, stage_dir or ".")
        elif (REPO / resolved).exists() and not resolved.startswith(".."):
            new = GITHUB_BLOB + resolved
        else:
            errors.append(f"{source}: link to missing file '{target}'")
            return match.group(0)
        return f"{match.group(1)}{new}{anchor}{match.group(3)}"

    return LINK.sub(fix, text)


def theme():
    """Copy the app's fonts and icons, and its tokens as Material color schemes.

    ui.css puts the light tokens on :root and the dark ones on .dark (the class
    the app's theme toggle sets); Material switches with data-md-color-scheme.
    """
    ui_css = (REPO / "frontend" / "assets" / "css" / "ui.css").read_text(encoding="utf-8")
    fonts = re.search(r"/\* -+ Fonts -+ \*/(.*?)/\* -+ Tokens -+ \*/", ui_css, re.S)
    tokens = re.search(r"/\* -+ Tokens -+ \*/(.*?)/\* -+ Base -+ \*/", ui_css, re.S)
    if not fonts or not tokens or ":root {" not in tokens.group(1) or ".dark {" not in tokens.group(1):
        sys.exit("frontend/assets/css/ui.css: Fonts or Tokens section not found")

    css = fonts.group(1).replace("url('../fonts/", "url('fonts/") + tokens.group(1)
    css = css.replace(":root {", ':root, [data-md-color-scheme="default"] {', 1)
    css = css.replace(".dark {", '[data-md-color-scheme="slate"] {', 1)
    assets = STAGE / "assets"
    assets.mkdir(parents=True, exist_ok=True)
    (assets / "ui-tokens.css").write_text(
        "/* Generated by website/stage.py from frontend/assets/css/ui.css */\n" + css,
        encoding="utf-8", newline="\n")

    shutil.copytree(REPO / "frontend" / "assets" / "fonts", assets / "fonts")
    for name in ("app-icon.svg", "favicon-32x32.png"):
        shutil.copy2(REPO / "frontend" / "assets" / "icons" / name, assets / name)


def main():
    if STAGE.exists():
        shutil.rmtree(STAGE)
    STAGE.mkdir(parents=True)

    mapping = pages()
    errors = []
    for source, staged in mapping.items():
        text = (REPO / source).read_text(encoding="utf-8")
        out = STAGE / staged
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(callouts(rewrite(source, text, mapping, errors)), encoding="utf-8", newline="\n")

    shutil.copytree(REPO / "images", STAGE / "images")
    shutil.copytree(REPO / "website" / "assets", STAGE / "assets")
    theme()

    if errors:
        print("\n".join(errors), file=sys.stderr)
        sys.exit(1)
    print(f"Staged {len(mapping)} pages in {STAGE.relative_to(REPO).as_posix()}")


if __name__ == "__main__":
    main()
